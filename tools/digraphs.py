#!/usr/bin/env python3
"""Generates crates/rim/src/editor/digraphs/table.rs from neovim's `digraphdefault`.

    python3 -I tools/digraphs.py path/to/neovim/src/nvim/digraph.c > crates/rim/src/editor/digraphs/table.rs

The table is the RFC1345 mnemonics (also vim's): facts about Unicode, so only the data is kept.
"""
import re
import sys

ENTRY = re.compile(r"\{\s*'((?:\\.|[^'\\])+)'\s*,\s*'((?:\\.|[^'\\])+)'\s*,\s*(0x[0-9a-fA-F]+)\s*\}")
ESCAPES = {"\\\\": "\\", "\\'": "'", '\\"': '"'}


def char(s):
    s = ESCAPES.get(s, s)
    if len(s) != 1:
        sys.exit(f"cannot read the character {s!r}")
    return ord(s)


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    start = src.index("digraphdefault[]")
    end = src.index("{ NUL, NUL, NUL }", start)
    seen = {}
    for m in ENTRY.finditer(src[start:end]):
        key = (char(m.group(1)), char(m.group(2)))
        # The first entry of a pair wins, like the linear scan of vim's table.
        seen.setdefault(key, int(m.group(3), 16))
    print("// Generated by tools/digraphs.py from the RFC1345 table of vim and neovim; do not edit.")
    print("pub(super) static DIGRAPHS: &[(u8, u8, u32)] = &[")
    for (a, b), code in sorted(seen.items()):
        print(f"    ({a}, {b}, 0x{code:04x}),")
    print("];")


main()
