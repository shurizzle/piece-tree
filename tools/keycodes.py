#!/usr/bin/env python3
"""Generates crates/rim/src/editor/script/keytable.rs from Neovim's key tables.

Usage: python3 -I tools/keycodes.py <neovim>/src/nvim > crates/rim/src/editor/script/keytable.rs

Reads `keycodes.lua` (the names), `keycodes.h` (`K_*`, `KS_*`, `KE_*`, `MOD_MASK_*`) and the
`modifier_keys_table` of `keycodes.c`, and writes the numbers (`TERMCAP2KEY(a, b)` is `-(a + (b << 8))`).
"""
import pathlib
import re
import sys

src = pathlib.Path(sys.argv[1])
lua = (src / "keycodes.lua").read_text()
header = (src / "keycodes.h").read_text()
c_src = (src / "keycodes.c").read_text()

consts = {}
# `#define KS_ZERO 255`, `#define MOD_MASK_SHIFT 0x02`, `#define KE_FILLER ('X')`.
for name, val in re.findall(r"^#define\s+((?:KS|KE|MOD_MASK)_\w+)\s+\(?([0-9a-fx]+|'.')\)?", header, re.M):
    consts[name] = ord(val[1]) if val.startswith("'") else int(val, 0)
# `KE_S_UP = 4,`.
for name, val in re.findall(r"^\s*(KE_\w+)\s*=\s*(\d+)\s*,", header, re.M):
    consts[name] = int(val)


def term(tok):
    tok = tok.strip()
    if tok.startswith("'"):
        return ord(tok[1:-1].replace("\\\\", "\\"))
    return consts[tok]


def termcap2key(a, b):
    return -(term(a) + (term(b) << 8))


keys = {}
for name, args in re.findall(r"^#define\s+(K_\w+)\s+TERMCAP2KEY\(([^)]*)\)", header, re.M):
    a, b = [x.strip() for x in args.split(",")]
    keys[name] = termcap2key(a, b)
# `K_ZERO` is the one written in terms of the macro of the header, and `K_NUL` is not a key of the table.
plain = {"TAB": 9, "NL": 10, "CAR": 13, "ESC": 27, "CSI": 0x9B, "' '": 32, "'|'": 124, "'\\\\'": 92, "'<'": 60}

entries = []
seen = set()
for key, name in re.findall(r"\{\s*\[\[(.+?)\]\],\s*'([^']+)'\s*\}", lua):
    num = plain[key] if key in plain else keys[key]
    entries.append((name, num, num in seen))
    seen.add(num)

table = re.search(r"modifier_keys_table\[\]\s*=\s*\{(.*?)\n\};", c_src, re.S).group(1)
table = re.sub(r"//[^\n]*", "", table)
mods = []
for line in table.split("\n"):
    m = re.match(r"\s*(MOD_MASK_\w+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*([^,]+),", line)
    if m:
        mask = consts[m.group(1)]
        mods.append((mask, termcap2key(m.group(2), m.group(3)), termcap2key(m.group(4), m.group(5))))

print("//! Generated by `tools/keycodes.py` from the `keycodes.lua`, `keycodes.h` and `keycodes.c` of Neovim: do not edit.")
print()
print("/// `key_names_table`: the name of a key as `keycodes.lua` gives it, its number (a char, or `-(a + (b << 8))` for a key with a code")
print("/// of its own) and whether the name is an alternative one (`is_alt`: an earlier entry has the key).")
print("pub(super) const KEY_NAMES: &[(&str, i32, bool)] = &[")
for name, num, alt in entries:
    print(f'    ("{name}", {num}, {"true" if alt else "false"}),')
print("];")
print()
print("/// `modifier_keys_table`: a modifier mask, the key that has the modifier in it and the key without it.")
print("pub(super) const MODIFIER_KEYS: &[(u32, i32, i32)] = &[")
for mask, w, wo in mods:
    print(f"    ({mask:#04x}, {w}, {wo}),")
print("];")
